// Builds the policy pages into public/ from legal/pages/*.html + legal/business.json.
// Run with:  npm run legal
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(DIR, '..', 'public');
const biz = JSON.parse(fs.readFileSync(path.join(DIR, 'business.json'), 'utf8'));

const PAGES = [
  { file: 'contact', title: 'Contact Us' },
  { file: 'terms', title: 'Terms & Conditions' },
  { file: 'privacy', title: 'Privacy Policy' },
  { file: 'refund', title: 'Refund & Cancellation Policy' },
  { file: 'shipping', title: 'Shipping & Delivery Policy' },
];

const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const todo = new Set();
function fill(html) {
  return html.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    if (!(key in biz)) throw new Error(`legal/business.json is missing "${key}"`);
    const v = String(biz[key]);
    if (/^\[.*\]$/.test(v)) { todo.add(key); return `<mark class="todo">${esc(v)}</mark>`; }
    return esc(v);
  });
}

const nav = PAGES.map((p) => `<a href="/${p.file}">${p.title}</a>`).join('\n        ');

for (const page of PAGES) {
  const body = fs.readFileSync(path.join(DIR, 'pages', `${page.file}.html`), 'utf8');
  const html = `<!doctype html>
<!-- Generated by legal/build.js. Edit legal/pages/${page.file}.html or legal/business.json, then run: npm run legal -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${page.title} · {{brand}}</title>
<meta name="description" content="${page.title} for {{brand}}, animated digital greeting cards.">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=DM+Sans:wght@400;500;700&family=Fraunces:opsz,wght@9..144,700;9..144,900&display=swap" rel="stylesheet">
<link rel="stylesheet" href="/style.css">
</head>
<body class="legal-body" data-theme="creator">
  <main class="legal">
    <nav class="legal-top">
      <a class="brand" href="/"><span class="logo">✦</span> {{brand}}</a>
      <a class="btn ghost small" href="/">Make a card</a>
    </nav>
    <article class="legal-card">
      <p class="lbl">Last updated: {{updated}}</p>
      <h1>${page.title}</h1>
${body}
    </article>
    <footer class="legal-footer">
      <nav>
        ${nav}
      </nav>
      <p>© {{brand}} · Operated by {{legalName}}</p>
    </footer>
  </main>
</body>
</html>
`;
  fs.writeFileSync(path.join(OUT, `${page.file}.html`), fill(html));
  console.log(`  ✓ public/${page.file}.html`);
}

if (todo.size) {
  console.log(`\n  ⚠ Still to fill in legal/business.json: ${[...todo].join(', ')}`);
  console.log('    (they show as highlighted boxes on the pages until you do)\n');
} else {
  console.log('\n  All details filled in. Pages are ready for Razorpay review.\n');
}
